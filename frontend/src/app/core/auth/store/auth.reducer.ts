import { createReducer, on } from '@ngrx/store';
import { AuthActions } from './auth.actions';
import { AuthState } from './auth.state';

export const initialAuthState: AuthState = {
  user: null,
  accessToken: null,
  refreshToken: null,
  isAuthenticated: false,
  hydrated: false,
  loading: false,
  error: null,
  sessionExpiredNotice: false,
  forbiddenError: null,
  activationStatus: 'idle',
  activationError: null,
  preferencesSaving: false,
  preferencesSaved: false,
  preferencesError: null,
};

export const authReducer = createReducer(
  initialAuthState,
  on(AuthActions.login, (state): AuthState => ({
    ...state,
    loading: true,
    error: null,
    sessionExpiredNotice: false,
    forbiddenError: null,
  })),
  on(AuthActions.loginSuccess, (state, { response }): AuthState => ({
    ...state,
    user: response.user,
    accessToken: response.accessToken,
    refreshToken: response.refreshToken,
    isAuthenticated: true,
    hydrated: true,
    loading: false,
    error: null,
    sessionExpiredNotice: false,
    forbiddenError: null,
  })),
  on(AuthActions.loginFailure, (state, { error }): AuthState => ({
    ...state,
    loading: false,
    error,
    isAuthenticated: false,
  })),
  on(AuthActions.refreshTokenSuccess, (state, { response }): AuthState => ({
    ...state,
    user: response.user,
    accessToken: response.accessToken,
    refreshToken: response.refreshToken,
    isAuthenticated: true,
    hydrated: true,
  })),
  on(AuthActions.refreshTokenFailure, (state, { error }): AuthState => ({
    ...state,
    user: null,
    accessToken: null,
    refreshToken: null,
    isAuthenticated: false,
    hydrated: true,
    error,
  })),
  on(AuthActions.hydrateSession, (state): AuthState => ({
    ...state,
    loading: true,
  })),
  on(
    AuthActions.hydrateSessionSuccess,
    (state, { user, accessToken, refreshToken }): AuthState => ({
      ...state,
      user,
      accessToken,
      refreshToken,
      isAuthenticated: true,
      hydrated: true,
      loading: false,
      error: null,
    }),
  ),
  on(AuthActions.hydrateSessionSkipped, (state): AuthState => ({
    ...state,
    user: null,
    accessToken: null,
    refreshToken: null,
    isAuthenticated: false,
    hydrated: true,
    loading: false,
  })),
  on(AuthActions.hydrateSessionFailure, (state, { error }): AuthState => ({
    ...state,
    user: null,
    accessToken: null,
    refreshToken: null,
    isAuthenticated: false,
    hydrated: true,
    loading: false,
    error,
  })),
  on(AuthActions.logoutCompleted, (state): AuthState => ({
    ...state,
    user: null,
    accessToken: null,
    refreshToken: null,
    isAuthenticated: false,
    hydrated: true,
    loading: false,
    error: null,
    sessionExpiredNotice: false,
    forbiddenError: null,
  })),
  on(AuthActions.sessionExpired, (state): AuthState => ({
    ...state,
    user: null,
    accessToken: null,
    refreshToken: null,
    isAuthenticated: false,
    hydrated: true,
    loading: false,
    sessionExpiredNotice: true,
    forbiddenError: null,
  })),
  on(AuthActions.forbiddenEncountered, (state, { error }): AuthState => ({
    ...state,
    forbiddenError: error,
  })),
  on(AuthActions.clearAuthError, (state): AuthState => ({
    ...state,
    error: null,
    sessionExpiredNotice: false,
    forbiddenError: null,
  })),
  on(AuthActions.activateAccount, (state): AuthState => ({
    ...state,
    activationStatus: 'loading',
    activationError: null,
  })),
  on(AuthActions.activateAccountSuccess, (state): AuthState => ({
    ...state,
    activationStatus: 'success',
    activationError: null,
  })),
  on(AuthActions.activateAccountFailure, (state, { error }): AuthState => ({
    ...state,
    activationStatus: 'error',
    activationError: error,
  })),
  on(AuthActions.resetActivationState, (state): AuthState => ({
    ...state,
    activationStatus: 'idle',
    activationError: null,
  })),
  on(AuthActions.updatePreferences, (state): AuthState => ({
    ...state,
    preferencesSaving: true,
    preferencesSaved: false,
    preferencesError: null,
  })),
  on(AuthActions.updatePreferencesSuccess, (state, { request }): AuthState => ({
    ...state,
    preferencesSaving: false,
    preferencesSaved: true,
    preferencesError: null,
    user: state.user
      ? {
          ...state.user,
          preferredLanguage: request.preferredLanguage ?? state.user.preferredLanguage,
          preferredTheme: request.preferredTheme ?? state.user.preferredTheme,
        }
      : null,
  })),
  on(AuthActions.updatePreferencesFailure, (state, { error }): AuthState => ({
    ...state,
    preferencesSaving: false,
    preferencesSaved: false,
    preferencesError: error,
  })),
  on(AuthActions.clearPreferencesFeedback, (state): AuthState => ({
    ...state,
    preferencesSaved: false,
    preferencesError: null,
  })),
);
